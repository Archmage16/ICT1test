def enrich_demo_events():
    changed = 0
    for index, (description, preparation) in enumerate(GUIDES, start=1):
        event = Olympiad.objects.filter(source_key=f"demo:{index}", is_demo=True).first()
        if not event:
            continue
        fields = []
        if not event.description or event.description == ORIGINAL_DESCRIPTION:
            event.description = description
            fields.append("description")
        for name, value in (
            ("participation_details", PARTICIPATION.get(event.format, "")),
            ("preparation", preparation),
            ("assessment", ASSESSMENT),
        ):
            if not getattr(event, name):
                setattr(event, name, value)
                fields.append(name)
        if fields:
            event.save(update_fields=fields)
            changed += 1
    return changed

